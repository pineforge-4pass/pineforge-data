template<std::size_t N> std::string bytes(const unsigned char (&data)[N]) { return std::string(reinterpret_cast<const char*>(data), N); }
void put_file(const std::string& path, const std::string& content) {
    std::ofstream file(path, std::ios::binary);
    file.write(content.data(), static_cast<std::streamsize>(content.size()));
    assert(file);
}
std::string inflated(const std::string& compressed, std::size_t chunk = 4096, std::size_t* calls = nullptr) {
    std::size_t offset = 0;
    std::string result;
    inflate([&](char* buffer, std::size_t limit) {
        const auto count = std::min({chunk, limit, compressed.size() - offset});
        std::memcpy(buffer, compressed.data() + offset, count);
        offset += count;
        return count;
    }, [&](std::string_view output) {
        result.append(output);
        if (calls) ++*calls;
    });
    return result;
}
std::string generated() {
    std::string text;
    for (int index = 0; index < 48; ++index) {
        char line[128];
        std::snprintf(line, sizeof(line), "%d,%d.%02d,0.%03d,%d,%d,%d,%s\n", 1000 + index, 10 + index * 7 % 13, index * 37 % 100,
                      index % 9 + 1, 5000 + 2 * index, 5001 + 2 * index, 120000 + 1500 * index, index % 2 ? "true" : "false");
        text += line;
    }
    return text;
}
// Deflate bits go least-significant first; Huffman codes are sent from their most significant bit.
struct Bits {
    std::string bytes;
    std::uint64_t buffer = 0;
    unsigned int count = 0;
    void put(std::uint32_t value, unsigned int width) {
        buffer |= static_cast<std::uint64_t>(value) << count;
        for (count += width; count >= 8; count -= 8, buffer >>= 8) bytes += static_cast<char>(buffer & 0xFF);
    }
    void huffman(std::uint32_t code, unsigned int width) {
        std::uint32_t reversed = 0;
        for (unsigned int bit = 0; bit < width; ++bit) reversed |= ((code >> bit) & 1U) << (width - 1 - bit);
        put(reversed, width);
    }
    std::string finish() {
        if (count) bytes += static_cast<char>(buffer & 0xFF);
        count = 0;
        return bytes;
    }
};
